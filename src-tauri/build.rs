fn main() {
    tauri_build::build();

    // Embed the entity type JSON templates at compile time so they are
    // available whether the app is run from source, installed, or portable.
    // Reading them from the filesystem next to the binary only works in dev;
    // an installed or portable app does not ship the `entity-types/` directory
    // alongside the executable.
    let entity_types_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("entity-types");
    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set"));

    let mut entries: Vec<(String, String)> = Vec::new();
    if let Ok(read_dir) = std::fs::read_dir(&entity_types_dir) {
        for entry in read_dir.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) == Some("json") {
                let stem = path
                    .file_stem()
                    .unwrap()
                    .to_str()
                    .unwrap()
                    .to_string();
                let content = std::fs::read_to_string(&path)
                    .unwrap_or_else(|e| panic!("Failed to read {}: {}", path.display(), e));
                entries.push((stem, content));
            }
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut rust_code = String::new();
    rust_code.push_str("// Entity type templates embedded at compile time.\n");
    rust_code.push_str("// Generated by build.rs - do not edit.\n\n");

    for (name, content) in &entries {
        let const_name = name.to_uppercase().replace('-', "_");
        rust_code.push_str(&format!(
            "pub const {}: &str = r#\"{}\"#;\n\n",
            const_name, content
        ));
    }

    rust_code.push_str("pub fn all_entity_type_jsons() -> Vec<&'static str> {\n");
    rust_code.push_str("    vec![\n");
    for (name, _) in &entries {
        let const_name = name.to_uppercase().replace('-', "_");
        rust_code.push_str(&format!("        {},\n", const_name));
    }
    rust_code.push_str("    ]\n");
    rust_code.push_str("}\n");

    let out_path = out_dir.join("entity_types.rs");
    std::fs::write(&out_path, rust_code).expect("Failed to write generated entity types");

    println!("cargo:rerun-if-changed=entity-types/");
}
