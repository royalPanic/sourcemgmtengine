/**
 * Generates `src/utils/worldOutline.ts` from Natural Earth 110m land polygons.
 *
 * Natural Earth is public domain (https://www.naturalearthdata.com/about/terms-of-use/).
 * The raw GeoJSON is ~138 KB; this simplifies and quantises it so the wireframe
 * can ship inside the bundle without a network request.
 *
 * Run with: node scripts/build-world-outline.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';

// Douglas-Peucker tolerance in degrees. 0.15 deg is ~17 km, which is invisible
// at the zoom levels this map is used at but removes most of the vertices.
const TOLERANCE = 0.15;
// Coordinates are rounded to this many decimals before deduplication.
// 2 decimals is ~1.1 km, which keeps coastal cities on the correct side of the
// shoreline; 1 decimal (~11 km) visibly moves coastlines past cities like New
// York and is not worth the few KB it saves.
const PRECISION = 2;

function perpendicularDistance(p, a, b) {
  const [x, y] = p;
  const [x1, y1] = a;
  const [x2, y2] = b;
  const dx = x2 - x1;
  const dy = y2 - y1;
  if (dx === 0 && dy === 0) return Math.hypot(x - x1, y - y1);
  const t = ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy);
  const clamped = Math.max(0, Math.min(1, t));
  return Math.hypot(x - (x1 + clamped * dx), y - (y1 + clamped * dy));
}

function simplify(points, tolerance) {
  if (points.length < 3) return points;

  let maxDist = 0;
  let index = 0;
  const first = points[0];
  const last = points[points.length - 1];

  for (let i = 1; i < points.length - 1; i += 1) {
    const dist = perpendicularDistance(points[i], first, last);
    if (dist > maxDist) {
      maxDist = dist;
      index = i;
    }
  }

  if (maxDist <= tolerance) return [first, last];

  const left = simplify(points.slice(0, index + 1), tolerance);
  const right = simplify(points.slice(index), tolerance);
  return [...left.slice(0, -1), ...right];
}

function round(value) {
  const factor = 10 ** PRECISION;
  return Math.round(value * factor) / factor;
}

/**
 * Rings are kept whole, including ones that cross the antimeridian or encircle
 * a pole. Splitting them would leave open arcs that cannot be filled, and
 * closing those arcs correctly is projection-dependent. The renderer instead
 * unwraps longitudes into a continuous sequence and clips with SVG, which
 * handles every case uniformly.
 */

function ringArea(ring) {
  let area = 0;
  for (let i = 0; i < ring.length; i += 1) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[(i + 1) % ring.length];
    area += x1 * y2 - x2 * y1;
  }
  return Math.abs(area / 2);
}

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Failed to fetch Natural Earth data: ${response.status}`);
}
const geojson = await response.json();

const rings = [];
let rawVertices = 0;

for (const feature of geojson.features) {
  const { geometry } = feature;
  if (!geometry) continue;

  const polygons =
    geometry.type === 'Polygon'
      ? [geometry.coordinates]
      : geometry.type === 'MultiPolygon'
        ? geometry.coordinates
        : [];

  for (const polygon of polygons) {
    for (const ring of polygon) {
      rawVertices += ring.length;

      // Drop tiny islands; they are sub-pixel at any usable zoom.
      if (ringArea(ring) < 0.35) continue;

      const simplified = simplify(ring, TOLERANCE);
      if (simplified.length < 3) continue;

      const flat = [];
      let lastLon = null;
      let lastLat = null;
      for (const [lon, lat] of simplified) {
        const rLon = round(lon);
        const rLat = round(lat);
        if (rLon === lastLon && rLat === lastLat) continue;
        flat.push(rLon, rLat);
        lastLon = rLon;
        lastLat = rLat;
      }

      if (flat.length >= 6) rings.push(flat);
    }
  }
}

const totalVertices = rings.reduce((sum, ring) => sum + ring.length / 2, 0);

const header = `// Generated by scripts/build-world-outline.mjs -- do not edit by hand.
//
// Simplified land outlines derived from Natural Earth 110m land polygons.
// Natural Earth is public domain: https://www.naturalearthdata.com/about/terms-of-use/
//
// Each ring is a flat [lon, lat, lon, lat, ...] array in degrees, kept whole
// even when it crosses the antimeridian or encircles a pole. The renderer
// unwraps longitudes and clips with SVG.

/** Land outlines as flat lon/lat pairs. */
export const WORLD_RINGS: readonly (readonly number[])[] = [
`;

const body = rings.map(ring => `  [${ring.join(',')}],`).join('\n');

const footer = `
];
`;

writeFileSync(
  join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'utils', 'worldOutline.ts'),
  header + body + footer,
  'utf8'
);

console.log(`raw vertices:      ${rawVertices}`);
console.log(`rings kept:        ${rings.length}`);
console.log(`vertices kept:     ${totalVertices}`);
console.log(`reduction:         ${(100 - (totalVertices / rawVertices) * 100).toFixed(1)}%`);
